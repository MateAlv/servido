from datetime import date, datetime, time
from uuid import UUID

from pydantic import BaseModel, Field

from app.schemas.table_inventory import MAX_TABLE_CAPACITY, SeatingArea


class SlotResponse(BaseModel):
    # "HH:MM", local to Buenos Aires.
    start_time: str
    # False when no table that seats the party is free for the whole block (US-11 S4).
    available: bool


class AvailabilityResponse(BaseModel):
    restaurant_id: UUID
    date: date
    open: bool
    duration_minutes: int
    max_party_size: int
    slots: list[SlotResponse]
    # The seating areas the restaurant has available tables in, in catalog order.
    seating_areas: list[SeatingArea]


class FreeGroupResponse(BaseModel):
    capacity: int
    seating_area: SeatingArea
    free: int


class TablesAvailabilityResponse(BaseModel):
    restaurant_id: UUID
    date: date
    start_time: str
    ends_at: datetime
    tables: list[FreeGroupResponse]


class TableChoice(BaseModel):
    """The table group the review showed: «Mesa para 4 · Terraza» (decision D2)."""

    capacity: int = Field(gt=0, le=MAX_TABLE_CAPACITY)
    seating_area: SeatingArea


class ReservationRequest(BaseModel):
    restaurant_id: UUID
    date: date
    start_time: time
    party_size: int = Field(ge=1, le=MAX_TABLE_CAPACITY)
    table: TableChoice
    # Generated by the page once per review; a repeated request returns the same reservation.
    request_id: UUID


class ReservationRestaurant(BaseModel):
    id: UUID
    nombre: str


class ReservationResponse(BaseModel):
    id: UUID
    restaurant: ReservationRestaurant
    date: date
    start_time: str
    end_time: str
    party_size: int
    table: TableChoice
    status: str


class DayReservationsResponse(BaseModel):
    date: date
    reservations: list[ReservationResponse]


class RestaurantReservationResponse(BaseModel):
    id: UUID
    start_time: str
    end_time: str
    party_size: int
    table: TableChoice
    status: str


class RestaurantReservationsResponse(BaseModel):
    restaurant_id: UUID
    date: date
    reservations: list[RestaurantReservationResponse]
